const ExcelJS = require('exceljs');
const PDFDocument = require('pdfkit');
const path = require('path');
const fs = require('fs');

const LOGO = path.join(__dirname, '..', 'public', 'img', 'suvarna-logo.png');
const hasLogo = () => fs.existsSync(LOGO);

const dmy = (iso) => (iso ? iso.slice(0, 10).split('-').reverse().join('-') + (iso.length > 10 ? ' ' + iso.slice(11, 16) : '') : '');
const stamp = () => {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}${p(d.getMonth() + 1)}${p(d.getDate())}-${p(d.getHours())}${p(d.getMinutes())}`;
};

const nowLocal = () => {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${p(d.getDate())}-${p(d.getMonth() + 1)}-${d.getFullYear()} ${p(d.getHours())}:${p(d.getMinutes())}`;
};

const COLUMNS = [
  { header: 'S.No', key: 'sno', width: 6, pdf: 28 },
  { header: 'Ticket Number', key: 'ticket_number', width: 16, pdf: 62 },
  { header: 'Client Name', key: 'client_name', width: 28, pdf: 84 },
  { header: 'Ticket Type', key: 'ticket_type', width: 14, pdf: 52 },
  { header: 'Department(s)', key: 'department_names', width: 26, pdf: 72 },
  { header: 'Approved Man-Days', key: 'approved_man_days', width: 12, pdf: 46, num: true },
  { header: 'Approved By', key: 'approved_by', width: 22, pdf: 66 },
  { header: 'Approved Date', key: 'approved_date', width: 14, pdf: 52, date: true },
  { header: 'Remarks', key: 'remarks', width: 40, pdf: 120 },
  { header: 'Created By', key: 'created_by_name', width: 20, pdf: 60 },
  { header: 'Created Date', key: 'created_at', width: 18, pdf: 58, date: true },
  { header: 'Last Updated By', key: 'updated_by_name', width: 20, pdf: 60 },
  { header: 'Last Updated Date', key: 'updated_at', width: 18, pdf: 58, date: true },
];

async function exportExcel(res, rows, filters, user) {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Ticket Tracking For Finance';
  wb.created = new Date();
  const ws = wb.addWorksheet('Man-Day Approvals', { views: [{ state: 'frozen', ySplit: 4 }] });

  ws.mergeCells(1, 1, 1, COLUMNS.length);
  ws.getCell(1, 1).value = 'Suvarna Technosoft · Ticket Tracking For Finance — Man-Day Approval Report';
  ws.getCell(1, 1).font = { bold: true, size: 14, color: { argb: 'FF2C6A98' } };
  ws.mergeCells(2, 1, 2, COLUMNS.length);
  ws.getCell(2, 1).value = `Generated by ${user.employee_name} on ${nowLocal()}   |   Filters: ${filters.length ? filters.join('; ') : 'None'}`;
  ws.getCell(2, 1).font = { size: 9, color: { argb: 'FF555555' } };
  ws.getRow(1).height = 30;
  ws.getRow(3).height = 18;
  if (hasLogo()) {
    const img = wb.addImage({ filename: LOGO, extension: 'png' });
    ws.addImage(img, { tl: { col: COLUMNS.length - 3, row: 0 }, ext: { width: 230, height: 53 } });
  }

  ws.columns = COLUMNS.map((c) => ({ key: c.key, width: c.width }));
  const header = ws.getRow(4);
  COLUMNS.forEach((c, i) => (header.getCell(i + 1).value = c.header));
  header.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  header.alignment = { vertical: 'middle', wrapText: true };
  header.height = 30;
  header.eachCell((cell) => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF2C6A98' } };
    cell.border = { bottom: { style: 'thin' } };
  });

  rows.forEach((r, i) => {
    const row = ws.addRow({
      ...r,
      sno: i + 1,
      approved_date: dmy(r.approved_date),
      created_at: dmy(r.created_at),
      updated_at: dmy(r.updated_at),
    });
    row.alignment = { vertical: 'top', wrapText: true };
    row.getCell('approved_man_days').numFmt = '0.##';
  });

  const total = rows.reduce((s, r) => s + r.approved_man_days, 0);
  const tr = ws.addRow({ client_name: `Total (${rows.length} tickets)`, approved_man_days: Math.round(total * 100) / 100 });
  tr.font = { bold: true };
  tr.getCell('approved_man_days').numFmt = '0.##';
  ws.autoFilter = { from: { row: 4, column: 1 }, to: { row: 4 + rows.length, column: COLUMNS.length } };

  res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
  res.setHeader('Content-Disposition', `attachment; filename="ManDay-Approvals-${stamp()}.xlsx"`);
  await wb.xlsx.write(res);
  res.end();
}

function exportPdf(res, rows, filters, user) {
  const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 30, bufferPages: true });
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="ManDay-Approvals-${stamp()}.pdf"`);
  doc.pipe(res);

  const left = doc.page.margins.left;
  const usable = doc.page.width - left - doc.page.margins.right;
  const scale = usable / COLUMNS.reduce((s, c) => s + c.pdf, 0);
  const widths = COLUMNS.map((c) => c.pdf * scale);
  const bottom = () => doc.page.height - doc.page.margins.bottom - 20;
  const pad = 3;

  if (hasLogo()) doc.image(LOGO, left + usable - 170, 24, { width: 170 });
  doc.font('Helvetica-Bold').fontSize(14).fillColor('#2C6A98').text('Ticket Tracking For Finance — Man-Day Approval Report', left, 30);
  doc.font('Helvetica').fontSize(8).fillColor('#555555')
    .text('Suvarna Technosoft Pvt Ltd')
    .text(`Generated by ${user.employee_name} on ${nowLocal()}`)
    .text(`Filters: ${filters.length ? filters.join('; ') : 'None'}`);
  const total = rows.reduce((s, r) => s + r.approved_man_days, 0);
  doc.font('Helvetica-Bold').fillColor('#222222').text(`Total tickets: ${rows.length}     Total approved man-days: ${Math.round(total * 100) / 100}`);
  doc.moveDown(0.6);

  const drawHeader = () => {
    doc.font('Helvetica-Bold').fontSize(7.5);
    const h = Math.max(...COLUMNS.map((c, i) => doc.heightOfString(c.header, { width: widths[i] - pad * 2 }))) + pad * 2;
    let x = left;
    const y = doc.y;
    doc.rect(left, y, usable, h).fill('#2C6A98');
    doc.fillColor('#FFFFFF');
    COLUMNS.forEach((c, i) => {
      doc.text(c.header, x + pad, y + pad, { width: widths[i] - pad * 2 });
      x += widths[i];
    });
    doc.y = y + h;
  };

  drawHeader();
  doc.font('Helvetica').fontSize(7.5);
  rows.forEach((r, idx) => {
    const values = COLUMNS.map((c) => {
      if (c.key === 'sno') return String(idx + 1);
      const v = r[c.key];
      if (v === null || v === undefined) return '';
      return c.date ? dmy(String(v)) : String(v);
    });
    doc.font('Helvetica').fontSize(7.5);
    const h = Math.max(...values.map((v, i) => doc.heightOfString(v || ' ', { width: widths[i] - pad * 2 }))) + pad * 2;
    if (doc.y + h > bottom()) {
      doc.addPage();
      doc.y = doc.page.margins.top;
      drawHeader();
      doc.font('Helvetica').fontSize(7.5);
    }
    const y = doc.y;
    if (idx % 2 === 1) doc.rect(left, y, usable, h).fill('#F2F5F9');
    doc.fillColor('#222222');
    let x = left;
    values.forEach((v, i) => {
      doc.text(v, x + pad, y + pad, { width: widths[i] - pad * 2, align: COLUMNS[i].num ? 'right' : 'left' });
      x += widths[i];
    });
    doc.moveTo(left, y + h).lineTo(left + usable, y + h).lineWidth(0.4).strokeColor('#D5DCE5').stroke();
    doc.y = y + h;
  });
  if (!rows.length) doc.font('Helvetica-Oblique').fontSize(9).fillColor('#555555').text('No records match the selected filters.', left, doc.y + 8);

  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    doc.font('Helvetica').fontSize(7).fillColor('#888888')
      .text(`Page ${i + 1} of ${range.count}`, left, doc.page.height - doc.page.margins.bottom - 10, { width: usable, align: 'right', lineBreak: false });
  }
  doc.end();
}

module.exports = { exportExcel, exportPdf };
